// ---------------------------------------------------------------------------
// WRITES dist/.well-known/security.txt (RFC 9116).
//
// WHAT IT BUYS. Someone who finds a flaw in this site currently has no way to
// say so. The realistic outcomes of that are a public disclosure, a report to
// the wrong address, or silence — and the last one is the most common. A
// security.txt is the difference between a researcher spending two minutes
// telling you and giving up. It costs one file.
//
// WHY IT IS GENERATED RATHER THAN CHECKED IN. RFC 9116 makes `Expires`
// mandatory, and a file with an expiry is a file that goes stale. A static
// public/.well-known/security.txt would be correct on the day it was written
// and quietly expired some months later, at which point tooling treats it as
// absent and it has bought nothing. Deriving the date from the build means
// every deploy renews it, and nobody has to remember — the same reasoning as
// scripts/emit-robots.mjs, which this sits beside.
//
// The window is deliberately short enough that a site which stops being
// deployed stops advertising a contact it may no longer be watching.
//
//   node scripts/emit-security-txt.mjs        (runs as part of `npm run build`)
// ---------------------------------------------------------------------------

import fs from 'node:fs';
import path from 'node:path';

const OUT_DIR = path.join('dist', '.well-known');
const OUT = path.join(OUT_DIR, 'security.txt');

/** Where a report should go. Overridable so the address can change without a
 *  code edit, and so a fork does not advertise Klay's inbox. */
const contact = (process.env.SECURITY_CONTACT || 'vedant@nogap.net.au').trim();

const deployUrl = (process.env.URL || process.env.DEPLOY_PRIME_URL || '').trim();
const canonical = (() => {
  if (!deployUrl) return null;
  try { return `${new URL(deployUrl).origin}/.well-known/security.txt`; } catch { return null; }
})();

/** 180 days. Long enough that a quiet month does not expire the file, short
 *  enough that an abandoned deploy stops pointing at a watched inbox. */
const EXPIRY_DAYS = 180;
const expires = new Date(Date.now() + EXPIRY_DAYS * 86_400_000).toISOString().replace(/\.\d{3}Z$/, 'Z');

// ASCII ONLY BELOW. Netlify serves .txt without a charset parameter, so a
// non-ASCII byte is decoded by whatever the reader guesses. The file is machine
// -read by disclosure tooling as often as by a person; an em-dash is not worth
// a mojibake risk in the one file whose job is to be unambiguous.
const body = `# Klay Interiors - security contact.
#
# GENERATED by scripts/emit-security-txt.mjs at build time. Do not edit by hand
# and do not commit a copy to public/: the Expires field below is derived from
# the build date so that it renews on every deploy. See the script's header.
#
# If you have found a vulnerability in this site, please tell us before telling
# anyone else. We will acknowledge your report and we will not pursue anyone
# who reports in good faith, stops at proof of concept, and does not access,
# modify or retain other people's data.
#
# Out of scope: denial of service, volumetric or automated scanning, social
# engineering of staff or customers, and findings from automated tools that
# have not been confirmed by hand.

Contact: mailto:${contact}
Expires: ${expires}
Preferred-Languages: en
${canonical ? `Canonical: ${canonical}\n` : ''}`;

if (!fs.existsSync('dist')) {
  console.error('emit-security-txt: no dist/ — run this after `vite build`.');
  process.exit(1);
}

if (!contact.includes('@')) {
  console.error(`emit-security-txt: SECURITY_CONTACT is not an email address (${contact || 'empty'}).`);
  process.exit(1);
}

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`emit-security-txt: contact ${contact}, expires ${expires}`);
